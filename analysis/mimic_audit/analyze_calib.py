"""Analyze the calibration run.

Reads the per-agent output files written by calib_workflow.js
(corpus/calib_out/mimic_<idx>.txt and disc_<idx>.txt), joins them with the
held-out tasks in corpus/calib_sample.json, and produces:

  1. STYLE MATCH: the mimic's fingerprint vs the real p10-p90 bands (in-band /
     OVER / UNDER per signature). OVER = caricature (the [OLD] failure mode).
  2. DISCRIMINATOR: Sonnet 4.6 accuracy at telling mimic from real, overall and
     per genre, as the two-sided metric |acc - 0.5| (0 = indistinguishable).

Writes CALIB_REPORT.md and corpus/calib_result.json. No API calls.
"""
from __future__ import annotations

import json
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

from fingerprint import features, NUMERIC, FRAC, pct, summarize

HERE = Path(__file__).resolve().parent
TAG = sys.argv[1] if len(sys.argv) > 1 else None
SAMPLE = HERE / "corpus" / (f"calib_sample_{TAG}.json" if TAG else "calib_sample.json")
OUTDIR = HERE / "corpus" / (f"calib_out_{TAG}" if TAG else "calib_out")
REALFP = HERE / "corpus" / "style_fingerprint.json"
REPORT = HERE / (f"CALIB_REPORT_{TAG}.md" if TAG else "CALIB_REPORT.md")
RESULT = HERE / "corpus" / (f"calib_result_{TAG}.json" if TAG else "calib_result.json")


def read_disc(idx: int):
    p = OUTDIR / f"disc_{idx}.txt"
    if not p.exists():
        return None
    pick = conf = tell = None
    for line in p.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.upper().startswith("PICK="):
            v = line.split("=", 1)[1].strip().upper()
            pick = "A" if v.startswith("A") else ("B" if v.startswith("B") else None)
        elif line.upper().startswith("CONF="):
            try:
                conf = float(line.split("=", 1)[1].strip())
            except ValueError:
                conf = None
        elif line.upper().startswith("TELL="):
            tell = line.split("=", 1)[1].strip()
    return {"pick": pick, "conf": conf, "tell": tell}


def main():
    payload = json.loads(SAMPLE.read_text(encoding="utf-8"))
    tasks = payload["tasks"]
    real_fp = json.loads(REALFP.read_text(encoding="utf-8"))["overall"]

    rows = []
    for t in tasks:
        idx = t["idx"]
        mp = OUTDIR / f"mimic_{idx}.txt"
        mimic = mp.read_text(encoding="utf-8").strip() if mp.exists() else None
        disc = read_disc(idx)
        real_is = "A" if idx % 2 == 0 else "B"
        correct = None
        if disc and disc["pick"] in ("A", "B"):
            correct = 1 if disc["pick"] == real_is else 0
        rows.append({
            "idx": idx, "theme": t["theme"], "kind": t["kind"],
            "position": t["position"], "cosine": t["cosine"], "mse": t["mse"],
            "prefix": t["prefix"], "real_av": t["real_av"], "mimic": mimic,
            "real_is": real_is,
            "pick": disc["pick"] if disc else None,
            "conf": disc["conf"] if disc else None,
            "tell": disc["tell"] if disc else None,
            "correct": correct,
        })

    have_mimic = [r for r in rows if r["mimic"]]
    judged = [r for r in rows if r["correct"] is not None]
    print(f"tasks={len(rows)} mimics_on_disk={len(have_mimic)} discriminated={len(judged)}")

    # ---- 1. fingerprint of the mimic ----
    mfeats = [features(r["mimic"]) for r in have_mimic]
    mimic_fp = summarize(mfeats)

    def band_verdict(sig):
        rp10, rp90 = real_fp[sig]["p10"], real_fp[sig]["p90"]
        mmed = mimic_fp[sig]["p50"]
        if mmed < rp10:
            return "UNDER"
        if mmed > rp90:
            return "OVER"
        return "in-band"

    # ---- 2. discriminator ----
    def acc(group):
        g = [r for r in group if r["correct"] is not None]
        return (sum(r["correct"] for r in g) / len(g), len(g)) if g else (None, 0)

    overall_acc, n_overall = acc(rows)
    by_genre = defaultdict(list)
    for r in rows:
        by_genre[r["theme"]].append(r)
    genre_acc = {g: acc(v) for g, v in sorted(by_genre.items())}

    two_sided = abs(overall_acc - 0.5) if overall_acc is not None else None
    direction = None
    if overall_acc is not None:
        if overall_acc > 0.58:
            direction = "DISTINGUISHABLE (judge tells them apart; mimic off-style or too clean)"
        elif overall_acc < 0.42:
            direction = "OVERSHOOT (judge picks the MIMIC as genuine; caricature, the [OLD] failure)"
        else:
            direction = "INDISTINGUISHABLE (near 50%, target hit)"

    # ---- report ----
    L = []
    L.append("# Calibration report: single mimic prompt v1")
    L.append("")
    L.append(f"Held-out eval: **{len(rows)} tasks** across 32 genres. "
             f"Mimics generated by Opus 4.8 from the full prefix; style judged by "
             f"Sonnet 4.6 (cross-model), no prefix shown. "
             f"Coverage: {len(have_mimic)} mimics, {len(judged)} discriminated.")
    L.append("")
    L.append("## 1. Style match (mimic fingerprint vs real p10-p90 bands)")
    L.append("")
    L.append("OVER = above the real band = caricature. UNDER = too clean. in-band = calibrated.")
    L.append("")
    L.append("| signature | real p10 | real med | real p90 | mimic med | mimic p10-p90 | verdict |")
    L.append("|---|---|---|---|---|---|---|")
    for k in NUMERIC:
        v = band_verdict(k)
        flag = "" if v == "in-band" else f" **{v}**"
        L.append(f"| {k} | {real_fp[k]['p10']} | {real_fp[k]['p50']} | {real_fp[k]['p90']} "
                 f"| {mimic_fp[k]['p50']} | {mimic_fp[k]['p10']}-{mimic_fp[k]['p90']} |{flag or ' in-band'} |")
    L.append("")
    L.append("| fraction signature | real | mimic | delta |")
    L.append("|---|---|---|---|")
    for k in FRAC:
        rf, mf = real_fp[k]["frac"], mimic_fp[k]["frac"]
        L.append(f"| {k} | {rf:.0%} | {mf:.0%} | {mf - rf:+.0%} |")
    L.append("")
    L.append("## 2. Cross-model discriminator (target: 50%)")
    L.append("")
    if overall_acc is not None:
        L.append(f"**Overall: {overall_acc:.1%}** (n={n_overall}). "
                 f"Two-sided |acc-0.5| = **{two_sided:.3f}**. {direction}")
    L.append("")
    L.append("| genre | n | disc acc | |acc-0.5| |")
    L.append("|---|---|---|---|")
    for g, (a, n) in genre_acc.items():
        if a is None:
            L.append(f"| {g} | 0 | n/a | n/a |")
        else:
            L.append(f"| {g} | {n} | {a:.0%} | {abs(a-0.5):.2f} |")
    L.append("")
    # a few discriminator tells (what gave the mimic away, when it did)
    tells = [r for r in judged if r["correct"] == 1 and r["tell"]]
    if tells:
        L.append("## What the discriminator used when it was right (sample tells)")
        L.append("")
        for r in tells[:12]:
            L.append(f"- *{r['theme']}* (conf {r['conf']}): {r['tell']}")
        L.append("")
    REPORT.write_text("\n".join(L), encoding="utf-8")

    result = {
        "n_tasks": len(rows), "n_mimic": len(have_mimic), "n_judged": len(judged),
        "overall_acc": overall_acc, "two_sided": two_sided, "direction": direction,
        "real_fp": real_fp, "mimic_fp": mimic_fp,
        "band_verdicts": {k: band_verdict(k) for k in NUMERIC},
        "genre_acc": {g: {"acc": a, "n": n} for g, (a, n) in genre_acc.items()},
        "rows": rows,
    }
    RESULT.write_text(json.dumps(result, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {REPORT.name} and {RESULT.name}")
    if overall_acc is not None:
        print(f"OVERALL disc acc = {overall_acc:.1%}  two-sided={two_sided:.3f}  {direction}")
    overs = [k for k in NUMERIC if band_verdict(k) == "OVER"]
    unders = [k for k in NUMERIC if band_verdict(k) == "UNDER"]
    print(f"fingerprint OVER: {overs or 'none'}")
    print(f"fingerprint UNDER: {unders or 'none'}")


if __name__ == "__main__":
    main()
